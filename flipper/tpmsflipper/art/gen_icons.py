"""icons.txt (ASCII art) -> ../wt_icons.h (XBM arrays for canvas_draw_xbm).

    python3 flipper/tpmsflipper/art/gen_icons.py          write the header
    python3 flipper/tpmsflipper/art/gen_icons.py --check  fail if it is out of date
"""
import sys
from pathlib import Path

here = Path(__file__).parent
icons, name = {}, None
for line in (here / 'icons.txt').read_text().splitlines():
    line = line.rstrip()
    if not line or line.startswith('#') and not set(line) <= set('#.'):
        continue
    if line.startswith('= '):
        name = line[2:].strip()
        icons[name] = []
    else:
        assert name and set(line) <= set('#.'), line
        icons[name].append(line)

out = ['// SPDX-License-Identifier: GPL-2.0-or-later', '#pragma once',
       '/* Generated by art/gen_icons.py from art/icons.txt. Do not edit by hand. */', '#include <stdint.h>', '']
for name, rows in icons.items():
    w, h = len(rows[0]), len(rows)
    assert all(len(r) == w for r in rows), name
    data = []
    for r in rows:
        for i in range(0, w, 8):
            data.append(sum(1 << b for b, ch in enumerate(r[i:i + 8]) if ch == '#'))
    out.append('#define WT_ICON_%s_W %d' % (name.upper(), w))
    out.append('#define WT_ICON_%s_H %d' % (name.upper(), h))
    out.append('static const uint8_t wt_icon_%s[] = {%s};' % (name, ', '.join('0x%02X' % b for b in data)))
text = '\n'.join(out) + '\n'
target = here.parent / 'wt_icons.h'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != text:
        raise SystemExit('FAIL: wt_icons.h is not what gen_icons.py makes from icons.txt')
    print('PASS: wt_icons.h matches art/icons.txt (%d icons)' % len(icons))
else:
    target.write_text(text)
    print('wrote %s (%d icons)' % (target, len(icons)))
