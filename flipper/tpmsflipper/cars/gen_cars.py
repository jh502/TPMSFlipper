"""cars.json -> the same car list for the Flipper app, the iPhone app and the docs.

    python3 flipper/tpmsflipper/cars/gen_cars.py          write the files
    python3 flipper/tpmsflipper/cars/gen_cars.py --check  fail if one is out of date

Writes, relative to the repository:
    flipper/tpmsflipper/wt_cars.h          data and list logic, SDK-free
    ios/TPMSFlipper/TPMSFlipper/SensorCars.swift   the same data for the iPhone app,
                                               where the repository has that app
    docs/CARS.md                    the table the documentation shows
"""
import json
import sys
import unicodedata
from pathlib import Path

here = Path(__file__).parent
repo = here.parent.parent.parent
data = json.loads((here / 'cars.json').read_text(encoding='utf-8'))
makes = data['makes']
HAS_IOS = (repo / 'ios/TPMSFlipper/TPMSFlipper').is_dir()  # the public repository has no iPhone app
STATUS = ['expected', 'recorded', 'tested']  # order = the C enum
WRAP = 22  # characters on one Flipper line; the screen test checks the pixels

for m in makes:
    assert m['status'] in STATUS, m
    assert m['bands'] and set(m['bands']) <= {433, 315}, m
    assert m['models'] and m['years'], m


def ascii_text(s):
    """The Flipper's small font has no accented letters."""
    return unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode()


def wrap(words, width):
    """Join "a, b, c" onto lines no longer than width; an item is never split."""
    lines, cur = [], ''
    for i, w in enumerate(words):
        piece = w + (',' if i + 1 < len(words) else '')
        assert len(piece) <= width, piece
        if cur and len(cur) + 1 + len(piece) > width:
            lines.append(cur)
            cur = piece
        else:
            cur = (cur + ' ' + piece) if cur else piece
    return lines + [cur]


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def band_bits(m):
    return (1 if 433 in m['bands'] else 0) | (2 if 315 in m['bands'] else 0)


# ----- Flipper ----------------------------------------------------------------
c = ['// SPDX-License-Identifier: GPL-2.0-or-later', '#pragma once',
     '/* Generated by cars/gen_cars.py from cars/cars.json. Do not edit by hand.',
     ' *',
     ' * TPMSFlipper: which cars are expected to carry the sensor this app reads.',
     ' * Header-only and SDK-free. Only one of these cars has been tried: the status',
     ' * of each make says which. See docs/CARS.md. */',
     '#include <stddef.h>', '#include <stdint.h>', '',
     '#define WT_CAR_B433 1u', '#define WT_CAR_B315 2u',
     'typedef enum { WT_CAR_EXPECTED = 0, WT_CAR_RECORDED, WT_CAR_TESTED } WtCarStatus;',
     'typedef struct {', '    const char* make;', '    uint8_t bands; /* WT_CAR_B433 | WT_CAR_B315 */',
     '    uint8_t status; /* WtCarStatus */', '    uint8_t nlines;',
     '    const char* const* lines; /* years, then the models, wrapped for the screen */', '} WtCarMake;', '']
for i, m in enumerate(makes):
    lines = [ascii_text(m['years'][0].upper() + m['years'][1:])] + wrap([ascii_text(x) for x in m['models']], WRAP)
    assert all(len(x) <= WRAP for x in lines), lines
    c.append('static const char* const wt_car_lines_%d[] = {%s};' % (i, ', '.join(c_str(x) for x in lines)))
    m['_nlines'] = len(lines)
c += ['', 'static const WtCarMake wt_cars[] = {']
for i, m in enumerate(makes):
    c.append('    {%s, %uu, %s, %u, wt_car_lines_%d},' % (
        c_str(ascii_text(m['make'])), band_bits(m), 'WT_CAR_' + m['status'].upper(), m['_nlines'], i))
c += ['};', '#define WT_CARS_COUNT %uu' % len(makes), '',
      '/* "433", "315" or "433/315": the sensor radio, MHz. */',
      'static inline const char* wt_car_bands(uint8_t bands) {',
      '    return bands == (WT_CAR_B433 | WT_CAR_B315) ? "433/315" : bands == WT_CAR_B315 ? "315" : "433";', '}',
      '/* One line for the foot of the screen. */',
      'static inline const char* wt_car_status(uint8_t status) {',
      '    return status == WT_CAR_TESTED ? "Tested on one car" :',
      '           status == WT_CAR_RECORDED ? "Recordings decode. Not tried" : "Expected. Not tried";', '}', '']

# ----- iPhone -----------------------------------------------------------------
s = ['// SPDX-License-Identifier: GPL-2.0-or-later',
     '// Generated by flipper/tpmsflipper/cars/gen_cars.py from cars.json. Do not edit by hand.',
     '//',
     '// Which cars are expected to carry the sensor TPMSFlipper reads. Only one of',
     '// these cars has been tried: each make says which. See docs/CARS.md.', '',
     'import Foundation', '',
     'struct SensorCarMake: Identifiable, Equatable {',
     '    enum Status: String { case expected, recorded, tested }',
     '    let make: String',
     '    let years: String',
     '    let models: [String]',
     '    let bands: [Int]  // the sensor radio, MHz',
     '    let status: Status',
     '    let note: String?',
     '    var id: String { make }',
     '}', '',
     'enum SensorCars {',
     '    static let sensor = %s' % json.dumps(data['sensor'], ensure_ascii=False),
     '    static let makes: [SensorCarMake] = [']
for m in makes:
    s.append('        SensorCarMake(make: %s, years: %s, models: [%s], bands: [%s], status: .%s, note: %s),' % (
        json.dumps(m['make'], ensure_ascii=False), json.dumps(m['years'], ensure_ascii=False),
        ', '.join(json.dumps(x, ensure_ascii=False) for x in m['models']), ', '.join(str(b) for b in m['bands']),
        m['status'], json.dumps(m['note'], ensure_ascii=False) if m.get('note') else 'nil'))
s += ['    ]', '',
      '    /// The makes whose name or one of whose models contains the text; all of them for no text.',
      '    static func matching(_ text: String) -> [SensorCarMake] {',
      '        let t = text.trimmingCharacters(in: .whitespaces)',
      '        guard !t.isEmpty else { return makes }',
      '        return makes.filter { m in',
      '            m.make.localizedStandardContains(t) || m.models.contains { $0.localizedStandardContains(t) }',
      '        }',
      '    }',
      '}', '']

# ----- docs -------------------------------------------------------------------
WORDS = {'tested': 'Tested', 'recorded': 'Recordings decode', 'expected': 'Expected, not tried'}
d = ['# Which cars use this sensor', '',
     '<!-- Generated by flipper/tpmsflipper/cars/gen_cars.py from cars.json. Do not edit by hand. -->', '',
     'TPMSFlipper reads one family of tyre sensor: %s.' % data['sensor'],
     'It has been run on **one car**, a Jaguar XF (X260). The rest of this list is',
     'cars for which a workshop tool uses the same wake signal, the same radio',
     'set-up and the same decoder as for that Jaguar. Nobody has tried this app on',
     'them. If you do, please say what happened.', '',
     *(['The Flipper app shows the same list under *Settings > Which cars?*, and the',
        'iPhone app under its menu.'] if HAS_IOS else
       ['The Flipper app shows the same list under *Settings > Which cars?*.']), '',
     '<img src="img/cars.png" width="256" alt="Which cars? on the Flipper"> <img src="img/car-1-0.png" width="256" alt="One make: years and models">', '',
     '| Make | Models | Years | Sensor radio, MHz | Status |', '|---|---|---|---|---|']
for m in makes:
    status = WORDS[m['status']] + (': ' + m['note'] if m.get('note') else '')
    d.append('| %s | %s | %s | %s | %s |' % (
        m['make'], ', '.join(m['models']), m['years'][0].upper() + m['years'][1:],
        ' and '.join(str(b) for b in m['bands']), status))
d += ['',
      '- **A model name is not a promise.** One model can carry different sensors in',
      '  different years and markets. The sure test is a scan at the wheel.',
      '- **433 or 315.** Cars sold in Europe use 433.92 MHz. Cars sold in North',
      '  America mostly use 315 MHz: set *Settings > Radio band* on the Flipper.',
      '- **"Recordings decode"** means published radio recordings of that car\'s',
      '  sensors read correctly with this app\'s decoder. Nothing was sent to one.',
      '- **Where the list comes from.** It is condensed from the vehicle table of a',
      '  workshop TPMS tool, not from the car makers.', '']

outputs = {
    repo / 'flipper/tpmsflipper/wt_cars.h': '\n'.join(c),
    **({repo / 'ios/TPMSFlipper/TPMSFlipper/SensorCars.swift': '\n'.join(s)} if HAS_IOS else {}),
    repo / 'docs/CARS.md': '\n'.join(d),
}
if '--check' in sys.argv:
    stale = [str(p.relative_to(repo)) for p, text in outputs.items()
             if not p.exists() or p.read_text(encoding='utf-8') != text]
    if stale:
        sys.exit('FAIL: out of date, run cars/gen_cars.py: ' + ', '.join(stale))
    print('PASS: the car list in %s matches cars.json (%u makes)' % (
        'the Flipper app, the iPhone app and the docs' if HAS_IOS else 'the Flipper app and the docs', len(makes)))
else:
    for p, text in outputs.items():
        p.write_text(text, encoding='utf-8')
    print('wrote ' + ', '.join(str(p.relative_to(repo)) for p in outputs))
