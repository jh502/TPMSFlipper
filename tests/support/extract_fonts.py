"""Write the four Flipper system fonts, as C arrays, from the SDK's firmware.elf.

The host renderer (gui/canvas.h in this folder) decodes them with the same
u8g2 glyph format the device uses, so string widths and glyph shapes in the
rendered screens are the device's. The font data is not kept in this repo: it
is read out of the pinned SDK each time.

    python3 tests/support/extract_fonts.py .build/ufbt-1.5.1-rc/current/firmware.elf out.h
"""
import struct, sys

WANT = {
    'u8g2_font_helvB08_tr': 'wt_font_primary',
    'u8g2_font_haxrcorp4089_tr': 'wt_font_secondary',
    'u8g2_font_profont11_mr': 'wt_font_keyboard',
    'u8g2_font_profont22_tn': 'wt_font_bignum',
}

elf = open(sys.argv[1], 'rb').read()
assert elf[:4] == b'\x7fELF' and elf[4] == 1 and elf[5] == 1, 'need a 32-bit little-endian ELF'
shoff, = struct.unpack_from('<I', elf, 0x20)
shentsize, shnum, shstrndx = struct.unpack_from('<HHH', elf, 0x2E)
sections = [struct.unpack_from('<IIIIIIIIII', elf, shoff + i * shentsize) for i in range(shnum)]


def addr_to_off(addr, size):
    for name, typ, flags, a, off, sz, link, info, align, ent in sections:
        if typ == 1 and a <= addr and addr + size <= a + sz:  # SHT_PROGBITS
            return off + addr - a
    raise SystemExit('address %x not in a section' % addr)


out = ['/* Generated by extract_fonts.py from the SDK firmware image. Do not commit. */']
found = set()
for name, typ, flags, a, off, sz, link, info, align, ent in sections:
    if typ != 2:  # SHT_SYMTAB
        continue
    stroff = sections[link][4]
    for i in range(sz // 16):
        st_name, st_value, st_size, st_info, st_other, st_shndx = struct.unpack_from('<IIIBBH', elf, off + i * 16)
        end = elf.index(b'\0', stroff + st_name)
        sym = elf[stroff + st_name:end].decode('ascii', 'replace')
        if sym in WANT and sym not in found:
            found.add(sym)
            data = elf[addr_to_off(st_value, st_size):][:st_size]
            out.append('static const unsigned char %s[%d] = {%s};' % (WANT[sym], st_size, ','.join(str(b) for b in data)))
missing = set(WANT) - found
assert not missing, 'fonts not found: %s' % missing
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
